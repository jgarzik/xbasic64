# BASIC Runtime: DATA/READ/RESTORE Support
#
# DATA Statement Overview:
#   DATA statements define constant values that READ takes in order. The
#   compiler collects every item into _data_table in the .data section.
#
# Data Table Format:
#   Each entry is 16 bytes:
#
#   Offset  Size  Content
#   ------  ----  -------
#   0       8     1 if the item was written in quotes, else 0
#   8       8     pointer to the item's text, NUL-terminated
#
# An item is kept as written, because GW-BASIC decides what it is when it is
# READ: `DATA 007` is the string "007" to READ A$ and the number 7 to READ A.
# A quoted item is a string only. The table used to tag items as integer,
# float or string at compile time, so READ A$ of 007 gave " 7".
#
# Global State:
#   _data_table = Array of 16-byte entries (generated by compiler)
#   _data_count = Number of entries in table
#   _data_ptr   = Current read position (0-based index)

# _rt_read_number - READ into a numeric variable
#
# The item's text must be a number and nothing else, read as VAL reads one
# (_rt_scan_number). Anything else -- a quoted item, or text that is not a
# number -- is GW-BASIC's "Syntax error" (2), reported for the READ; an empty
# item is 0. This used to strtod a string item, so DATA "abc" read as 0.
#
# Arguments:
#   rdi = BASIC line number, for the diagnostic
#
# Returns:
#   xmm0 = value as double; 0 when there is nothing to read
#
# Side effect: Advances _data_ptr to next entry
#
# Reading past the last item raises Out of DATA (error 4).
.globl _rt_read_number
_rt_read_number:
    push rbp
    mov rbp, rsp
    push rbx
    push r12
    push r13
    push r14
    mov r12, rdi                        # line number
    mov rax, QWORD PTR [rip + _data_ptr]
    cmp rax, QWORD PTR [rip + _data_count]
    jae .Lread_num_none
    inc QWORD PTR [rip + _data_ptr]
    shl rax, 4
    lea rcx, [rip + _data_table]
    add rcx, rax                        # the entry
    cmp QWORD PTR [rcx], 0
    jne .Lread_num_syntax               # quoted: a string, not a number
    mov rbx, QWORD PTR [rcx + 8]        # its text
    mov rdi, rbx
    call strlen
    mov r13, rax                        # its length
    test r13, r13
    jz .Lread_num_zero                  # an empty item is 0
    mov rdi, rbx
    mov rsi, r13
    call _rt_scan_number
    test edx, edx
    jnz .Lread_num_overflow
    test rax, rax
    jz .Lread_num_syntax
    # Only blanks may follow the number.
.Lread_num_rest:
    cmp rax, r13
    jae .Lread_num_done
    movzx ecx, BYTE PTR [rbx + rax]
    cmp ecx, 32
    je .Lread_num_blank
    cmp ecx, 9
    jne .Lread_num_syntax
.Lread_num_blank:
    inc rax
    jmp .Lread_num_rest

.Lread_num_none:
    lea rdi, [rip + _err_outofdata]
    jmp .Lread_num_raise
.Lread_num_syntax:
    lea rdi, [rip + _err_syntax]
    jmp .Lread_num_raise
.Lread_num_overflow:
    lea rdi, [rip + _err_overflow]
.Lread_num_raise:
    mov rsi, r12                        # line
    call _rt_error                      # returns only when trapped
.Lread_num_zero:
    xorpd xmm0, xmm0
.Lread_num_done:
    pop r14
    pop r13
    pop r12
    pop rbx
    leave
    ret

# _rt_read_string - READ into a string variable
#
# The item's text, as written: a quoted item without its quotes, an unquoted
# one as the DATA statement spelled it, so `DATA 007` reads as "007".
#
# Arguments:
#   rdi = BASIC line number, for the diagnostic
#
# Returns:
#   rax = pointer to string data
#   rdx = string length; an empty string when there is nothing to read
#
# Side effect: Advances _data_ptr to next entry
.globl _rt_read_string
_rt_read_string:
    push rbp
    mov rbp, rsp
    push rbx
    sub rsp, 8
    mov rax, QWORD PTR [rip + _data_ptr]
    cmp rax, QWORD PTR [rip + _data_count]
    jae .Lread_str_none
    inc QWORD PTR [rip + _data_ptr]
    shl rax, 4
    lea rcx, [rip + _data_table]
    mov rbx, QWORD PTR [rcx + rax + 8]  # the text
    mov rdi, rbx
    call strlen                         # DATA text is NUL-terminated
    mov rdx, rax
    mov rax, rbx
    add rsp, 8
    pop rbx
    leave
    ret
.Lread_str_none:
    mov rsi, rdi                        # line
    lea rdi, [rip + _err_outofdata]
    call _rt_error                      # returns only when trapped
    xor eax, eax
    xor edx, edx
    add rsp, 8
    pop rbx
    leave
    ret

# _rt_restore - Reset DATA pointer (RESTORE statement)
#
# Arguments:
#   rdi = new position (0-based index into data table); RESTORE with no
#         argument passes 0, RESTORE n the index of the first item at or
#         after line n
#
# Returns: nothing
.globl _rt_restore
_rt_restore:
    mov QWORD PTR [rip + _data_ptr], rdi
    ret

# _rt_array_autodim - Create an array by using it, as GW-BASIC does
#
# Called when an array is reached with no storage: never DIMmed, or ERASEd.
# Every dimension runs from the OPTION BASE to 10, and the elements start as
# zeros -- 0 and "" alike. A use of an array before its DIM used to be the
# error "Array used before DIM".
#
# Arguments:
#   rdi = the descriptor: word 0 the element pointer, word 1+i dimension i's
#         element count, word 1+n+i its lower bound
#   rsi = n, the number of dimensions
#   rdx = element size in bytes
#   rcx = the OPTION BASE
# Returns: nothing (Out of memory leaves the pointer null)
.globl _rt_array_autodim
_rt_array_autodim:
    push rbp
    mov rbp, rsp
    push rbx
    push r12
    mov rbx, rdi            # descriptor
    mov r12, rdx            # running size: element size * the counts
    mov eax, 11
    sub rax, rcx            # elements per dimension: base..10
    xor r8d, r8d            # dimension
.Lautodim_dim:
    cmp r8, rsi
    jae .Lautodim_alloc
    mov QWORD PTR [rbx + 8 + r8*8], rax
    lea r9, [rsi + r8]
    mov QWORD PTR [rbx + 8 + r9*8], rcx
    imul r12, rax
    inc r8
    jmp .Lautodim_dim
.Lautodim_alloc:
    mov edi, 1
    mov rsi, r12
    call calloc
    test rax, rax
    jz .Lautodim_nomem
    mov QWORD PTR [rbx], rax
    pop r12
    pop rbx
    leave
    ret
.Lautodim_nomem:
    lea rdi, [rip + _err_memory]
    xor esi, esi
    call _rt_error          # returns only when trapped
    pop r12
    pop rbx
    leave
    ret
